// prices.csv.gz is generated by hack/prices: run `make prices`.
//
//go:embed prices.csv.gz
var pricesFile []byte

// NodeType is how a node is priced, from its well-known labels.
type NodeType struct {
	InstanceType string `json:"instanceType"`
	Region       string `json:"region"`
	Spot         bool   `json:"spot,omitempty"`
}

// spotLabels mark a node as spot or preemptible capacity, whose price
// changes by the hour; it's priced at on-demand.
var spotLabels = map[string]string{
	"karpenter.sh/capacity-type":            "spot",
	"eks.amazonaws.com/capacityType":        "SPOT",
	"cloud.google.com/gke-spot":             "true",
	"cloud.google.com/gke-preemptible":      "true",
	"kubernetes.azure.com/scalesetpriority": "spot",
}

// NodeTypeOf reads a node's instance type, region, and whether it's spot
// from its labels.
func NodeTypeOf(labels map[string]string) NodeType {
	t := NodeType{
		InstanceType: labels["node.kubernetes.io/instance-type"],
		Region:       labels["topology.kubernetes.io/region"],
	}
	for key, value := range spotLabels {
		if labels[key] == value {
			t.Spot = true
		}
	}
	return t
}

// ListPrice is a node type's on-demand list price, as rates.
type ListPrice struct {
	Provider string
	Rates    Rates
}

var listed = struct {
	sync.Mutex
	prices map[NodeType]*ListPrice
}{prices: map[NodeType]*ListPrice{}}

// ListPriceOf is a node type's on-demand list price, and false when the
// table doesn't have it. A cluster has few node types, so each is looked up
// in the table once, rather than the table kept in memory.
func ListPriceOf(t NodeType) (ListPrice, bool) {
	key := NodeType{InstanceType: t.InstanceType, Region: t.Region}
	listed.Lock()
	defer listed.Unlock()
	p, seen := listed.prices[key]
	if !seen {
		found, ok, err := lookUp(t.InstanceType, t.Region)
		if err != nil {
			return ListPrice{}, false
		}
		if ok {
			p = &found
		}
		listed.prices[key] = p
	}
	if p == nil {
		return ListPrice{}, false
	}
	return *p, true
}

// cpuToMemory is what a vCPU costs against a GiB of memory, from the
// default rates, which are AWS's general-purpose instances. Providers
// price an instance as a whole, so this is how its price is split between
// what its pods request.
var cpuToMemory = DefaultRates.CPUPerHour / DefaultRates.MemoryPerHour

// splitHourly divides an instance's hourly price between its vCPUs and its
// memory in the default rates' proportion, so a memory-optimized instance's
// memory and a compute-optimized one's CPU come out at what they cost there.
func splitHourly(hourly, vcpu, memoryGiB float64) Rates {
	perGiB := hourly / (vcpu*cpuToMemory + memoryGiB)
	return Rates{CPUPerHour: perGiB * cpuToMemory, MemoryPerHour: perGiB, StoragePerMonth: DefaultRates.StoragePerMonth}
}

// tableName is how the table names an instance type. Instance type names
// don't collide across providers, so the provider isn't needed to find one.
// AKS labels nodes with the ARM size name, Standard_D4s_v5, which the
// table has as d4sv5.
//
// An Azure constrained vCPU size, such as Standard_E4-2s_v5, is its base
// size, E4s_v5, with only some of the vCPUs, 2, enabled. Azure bills it as
// the base size, and the table lists only base sizes, so it's found as the
// base size and vcpus says how many of its vCPUs its price is spread over;
// zero for any other instance type.
func tableName(instanceType string) (name string, vcpus float64) {
	t := strings.ToLower(instanceType)
	rest, ok := strings.CutPrefix(t, "standard_")
	if !ok {
		return t, 0
	}
	return constrainedBase(strings.ReplaceAll(rest, "_", ""))
}

// constrainedBase splits a constrained vCPU size, e4-2sv5, into its base
// size, e4sv5, and its enabled vCPUs, 2.
func constrainedBase(size string) (base string, vcpus float64) {
	head, tail, ok := strings.Cut(size, "-")
	if !ok || head == "" || !isDigit(head[len(head)-1]) {
		return size, 0
	}
	n := 0
	for n < len(tail) && isDigit(tail[n]) {
		n++
	}
	enabled, err := strconv.Atoi(tail[:n])
	if err != nil || enabled == 0 {
		return size, 0
	}
	return head + tail[n:], float64(enabled)
}

func isDigit(c byte) bool { return '0' <= c && c <= '9' }

// lookUp finds an instance type's price in a region in the table.
func lookUp(instanceType, region string) (ListPrice, bool, error) {
	if instanceType == "" || region == "" {
		return ListPrice{}, false, nil
	}
	name, vcpus := tableName(instanceType)
	region = strings.ToLower(region)
	gz, err := gzip.NewReader(bytes.NewReader(pricesFile))
	if err != nil {
		return ListPrice{}, false, fmt.Errorf("reading the price table: %w", err)
	}
	sc := bufio.NewScanner(gz)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for line := 1; sc.Scan(); line++ {
		fields := strings.Split(sc.Text(), ",")
		if len(fields) < 5 || fields[1] != name {
			continue
		}
		for _, field := range fields[4:] {
			r, price, _ := strings.Cut(field, "=")
			if r != region {
				continue
			}
			p, err := parseListing(fields, price, line, vcpus)
			return p, err == nil, err
		}
		return ListPrice{}, false, nil
	}
	if err := sc.Err(); err != nil {
		return ListPrice{}, false, fmt.Errorf("reading the price table: %w", err)
	}
	return ListPrice{}, false, nil
}

// parseListing reads a table line's price in one region, spread over enabled
// vCPUs when they're fewer than the instance type's.
func parseListing(fields []string, price string, line int, enabled float64) (ListPrice, error) {
	vcpu, err := strconv.ParseFloat(fields[2], 64)
	if err != nil {
		return ListPrice{}, fmt.Errorf("price table line %d: vCPUs: %w", line, err)
	}
	memory, err := strconv.ParseFloat(fields[3], 64)
	if err != nil {
		return ListPrice{}, fmt.Errorf("price table line %d: memory: %w", line, err)
	}
	hourly, err := strconv.ParseFloat(price, 64)
	if err != nil {
		return ListPrice{}, fmt.Errorf("price table line %d: price: %w", line, err)
	}
	if enabled > 0 && enabled < vcpu {
		vcpu = enabled
	}
	return ListPrice{Provider: fields[0], Rates: splitHourly(hourly, vcpu, memory)}, nil
}

// Mean averages the rates of a workload's pods, which request the same, so
// it's what the workload costs per vCPU and GiB across the nodes it runs on.
func Mean(rates []Rates) Rates {
	var m Rates
	for _, r := range rates {
		m.CPUPerHour += r.CPUPerHour
		m.MemoryPerHour += r.MemoryPerHour
		m.StoragePerMonth += r.StoragePerMonth
	}
	n := float64(len(rates))
	if n == 0 {
		return m
	}
	m.CPUPerHour /= n
	m.MemoryPerHour /= n
	m.StoragePerMonth /= n
	return m
}
